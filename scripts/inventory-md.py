#!/usr/bin/env python3
"""
Render docs/inventory CSVs (components, network) into read-only markdown summaries.

Usage (call from repo root): python3 scripts/inventory-md.py
"""

import csv
from collections import Counter
from pathlib import Path

inventory_dir = Path(__file__).resolve().parent.parent / "docs" / "inventory"
components_dir = inventory_dir / "components"


def fmt_capacity(gb):
    if not gb:
        return ""
    gb = int(gb)
    return f"{gb // 1000}TB" if gb >= 1000 and gb % 1000 == 0 else f"{gb}GB"


# Extra details shown in brackets after brand + model, keyed by CSV name
details = {
    "ram": lambda row: [row["ddr_gen"].upper(), fmt_capacity(row["capacity_gb"])],
    "storage": lambda row: [row["type"].upper(), fmt_capacity(row["capacity_gb"])],
    "network": lambda row: [f'{row["ports"]}-port' if row["ports"] else "", row["speed"]],
}


def label(row, stem):
    # nic.csv has no model, only chipset
    name = " ".join(filter(None, (row.get("brand"), row.get("model") or row.get("chipset"))))
    extra = ", ".join(filter(None, details[stem](row))) if stem in details else ""
    return f"{name} ({extra})" if extra else name


def render(title, csv_paths, output):
    lines = [
        f"# {title}",
        "",
        "<!-- Generated by scripts/inventory-md.py - edit the CSVs, not this file -->",
    ]

    csv_paths = sorted(csv_paths)
    for csv_path in csv_paths:
        with csv_path.open(newline="") as f:
            counts = Counter(label(row, csv_path.stem) for row in csv.DictReader(f))

        # Single-CSV pages don't need a sub-heading repeating the title
        if len(csv_paths) > 1:
            stem = csv_path.stem
            heading = stem.upper() if len(stem) <= 3 else stem.title()
            lines += ["", f"## {heading}"]
        lines.append("")
        lines += [f"- **{count}×** {name}" for name, count in counts.items()]

    output.write_text("\n".join(lines) + "\n")
    print(f"wrote {output}")


render("Components", components_dir.glob("*.csv"), inventory_dir / "components.md")
render("Network", [inventory_dir / "network.csv"], inventory_dir / "network.md")
